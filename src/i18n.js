let currentLang = "en";

/** 由瀏覽器語言（如 zh-TW、ja-JP）對應到支援的語言；用於後端回報語言之前的初始畫面。 */
function langFromLocale(loc) {
  const l = String(loc || "").toLowerCase().replace("_", "-");
  if (l.startsWith("zh")) return /(^|-)(tw|hk|mo|hant)(-|$)/.test(l) ? "zh-TW" : "zh-CN";
  if (l.startsWith("ja")) return "ja";
  return "en";
}

function setLang(code) {
  currentLang = LANGS.includes(code) ? code : "en";
  document.documentElement.lang = currentLang;
}

/** 查字典並代入 {變數}；找不到鍵時回傳鍵本身，讓缺漏一眼可見。 */
function t(key, vars) {
  let s = (DICT[currentLang] && DICT[currentLang][key]) ?? DICT.en[key] ?? key;
  for (const [k, v] of Object.entries(vars || {})) s = s.split(`{${k}}`).join(v);
  return s;
}

/** 套用到靜態 HTML：data-i18n 換文字；data-i18n-attr="屬性:鍵;屬性:鍵" 換屬性。 */
function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":");
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  });
}
